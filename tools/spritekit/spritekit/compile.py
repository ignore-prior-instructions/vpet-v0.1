"""`spritekit compile`: turns everything under `assets/` into
`crates/vpet-core/src/assets/generated.rs`. See docs/CONTENT.md and docs/adr/0009. Refuses to
emit if any validator error remains, or (by default) if any species pose is missing from
`assets/approved.lock` or has changed since it was approved.

Sprites are emitted as inline byte-array literals (`Sprite { w, h, rows: &[0x.., ..] }`) rather
than named `static`s: Rust promotes a `&[u8]` array literal inside a `static`/`const` initializer
to `'static` automatically, so there's no need to invent a unique Rust identifier per pose —
which matters because font glyph names like "0".."9" aren't valid Rust identifiers anyway.
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from .approve import unapproved_or_changed_poses
from .grid import bbox as compute_bbox, pack_image, pack_mask, parse
from .spec import Spec
from .validate import validate_all

HEADER = """\
// GENERATED by `spritekit compile` from assets/ (see docs/CONTENT.md, docs/adr/
// 0009-assets-compiled-in-checked-in-codegen.md). Do not hand-edit: edit the text grids or
// species.toml under assets/ and run `spritekit compile` again. CI runs `spritekit compile
// --check` to keep this file honest.

use crate::assets::{{GameRules, Pose, Sprite, SpeciesDef, StageRules, StageSet}};

pub const CONTENT_HASH: u32 = 0x{content_hash:08x};
"""


class CompileError(Exception):
    pass


def _fnv1a(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


@dataclass
class Emitter:
    hash_input: bytearray = field(default_factory=bytearray)

    def rust_bytes(self, data: bytes) -> str:
        self.hash_input.extend(data)
        return "&[" + ", ".join(f"0x{b:02X}" for b in data) + "]"

    def sprite_literal(self, sprite, w: int, h: int) -> str:
        img = pack_image(sprite.rows, w)
        return f"Sprite {{ w: {w}, h: {h}, rows: {self.rust_bytes(img)} }}"

    def pose_literal(self, sprite, w: int, h: int, default_mouth) -> str:
        img = pack_image(sprite.rows, w)
        mask = pack_mask(sprite.rows, w)
        bb = compute_bbox(sprite.rows, w, h)
        mouth = sprite.mouth if sprite.mouth is not None else default_mouth(bb)
        blink = (
            f"Some(Sprite {{ w: {w}, h: {h}, rows: {self.rust_bytes(mask)} }})"
            if mask is not None
            else "None"
        )
        bbox_str = f"({bb[0]}, {bb[1]}, {bb[2]}, {bb[3]})" if bb else "(0, 0, 0, 0)"
        return (
            f"Pose {{ img: Sprite {{ w: {w}, h: {h}, rows: {self.rust_bytes(img)} }}, "
            f"blink: {blink}, mouth: ({mouth[0]}, {mouth[1]}), bbox: {bbox_str} }}"
        )


def _default_mouth(bb) -> tuple[int, int]:
    """docs/art/SPRITE_FORMAT.md's default: leftmost on-pixel at 60% bbox height. Callers only
    reach this for poses without an explicit `@mouth` header; a reasonable fallback when there
    is no bbox at all (a blank pose) is the cell centre-ish, which nothing should ever render."""
    if bb is None:
        return (7, 9)
    x0, y0, x1, y1 = bb
    y = round(y0 + 0.6 * (y1 - y0))
    return (x0, y)


def _load_global(assets_root: Path, name: str):
    f = assets_root / "global" / f"{name}.txt"
    return parse(str(f), f.read_text(encoding="utf-8"))


def _species_toml(species_dir: Path) -> dict:
    with open(species_dir / "species.toml", "rb") as f:
        return tomllib.load(f)


def _stage_rules(stage_toml: dict) -> str:
    lo, hi = stage_toml.get("poop_interval_secs", [7200, 10800])
    stage_secs = stage_toml.get("stage_secs", 0)
    return (
        f"StageRules {{ hunger_step_secs: {stage_toml['hunger_step_secs']}, "
        f"happy_step_secs: {stage_toml['happy_step_secs']}, "
        f"poop_interval_min_secs: {lo}, poop_interval_max_secs: {hi}, "
        f"stage_secs: {stage_secs} }}"
    )


def _compile_stage_set(em: Emitter, gf, stage_toml: dict) -> str:
    by_name = {s.name: s for s in gf.sprites}

    def pose(name: str) -> str:
        s = by_name[name]
        return em.pose_literal(s, gf.cell_w, gf.cell_h, _default_mouth)

    def optional_pose(name: str) -> str:
        s = by_name.get(name)
        return "None" if s is None else f"Some({em.pose_literal(s, gf.cell_w, gf.cell_h, _default_mouth)})"

    required = ["idle_a", "idle_b", "happy", "eat", "sleep"]
    missing = [p for p in required if p not in by_name]
    if missing:
        raise CompileError(f"{gf.path}: missing required pose(s): {missing}")

    return (
        "StageSet {\n"
        f"    idle_a: {pose('idle_a')},\n"
        f"    idle_b: {pose('idle_b')},\n"
        f"    happy: {pose('happy')},\n"
        f"    eat: {pose('eat')},\n"
        f"    sleep: {pose('sleep')},\n"
        f"    sad: {optional_pose('sad')},\n"
        f"    attack: {optional_pose('attack')},\n"
        f"    rules: {_stage_rules(stage_toml)},\n"
        "}"
    )


def _compile_species(em: Emitter, assets_root: Path, slug: str) -> str:
    species_dir = assets_root / "species" / slug
    toml = _species_toml(species_dir)
    sp = toml["species"]
    schedule = toml["schedule"]
    assets_cfg = toml.get("assets", {})

    stage_files = {}
    for stage in ("baby", "child", "adult"):
        f = species_dir / f"{stage}.txt"
        stage_files[stage] = parse(str(f), f.read_text(encoding="utf-8"))

    adult_alt_str = "None"
    if assets_cfg.get("adult_alt", False):
        f = species_dir / "adult_alt.txt"
        if not f.is_file():
            raise CompileError(f"{slug}: species.toml declares adult_alt=true but {f} is missing")
        gf = parse(str(f), f.read_text(encoding="utf-8"))
        adult_alt_str = f"Some({_compile_stage_set(em, gf, toml['stages']['adult'])})"

    egg_str = "None"
    if assets_cfg.get("egg_override", False):
        raise CompileError(f"{slug}: egg_override=true is not yet implemented by compile.py")

    return (
        "SpeciesDef {\n"
        f"    id: {sp['id']},\n"
        f'    slug: "{sp["slug"]}",\n'
        f'    name: "{sp["name"]}",\n'
        f"    hatch_secs: {sp['hatch_secs']},\n"
        f"    schedule: ({schedule['awake_secs']}, {schedule['sleep_secs']}),\n"
        f"    egg: {egg_str},\n"
        f"    baby: {_compile_stage_set(em, stage_files['baby'], toml['stages']['baby'])},\n"
        f"    child: {_compile_stage_set(em, stage_files['child'], toml['stages']['child'])},\n"
        f"    adult: {_compile_stage_set(em, stage_files['adult'], toml['stages']['adult'])},\n"
        f"    adult_alt: {adult_alt_str},\n"
        "}"
    )


