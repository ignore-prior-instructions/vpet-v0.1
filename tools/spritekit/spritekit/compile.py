def compile_source(assets_root: Path, spec: Spec, allow_unapproved: bool = False) -> str:
    reports = validate_all(assets_root, spec)
    bad = [r for r in reports if not r.ok]
    if bad:
        lines = [f"{r.file}::{r.sprite}: {e}" for r in bad for e in r.errors]
        raise CompileError("validation failed:\n" + "\n".join(lines))

    registry_path = assets_root / "registry.toml"
    registry = tomllib.loads(registry_path.read_text(encoding="utf-8")).get("species", [])

    if not allow_unapproved:
        for entry in registry:
            problems = unapproved_or_changed_poses(assets_root, entry["slug"])
            if problems:
                raise CompileError(
                    f"{entry['slug']}: unapproved poses (run `spritekit approve {entry['slug']}`, "
                    f"or pass --allow-unapproved for a dev build):\n" + "\n".join(problems)
                )

    em = Emitter()

    icons_gf = _load_global(assets_root, "icons")
    icon_names = spec.global_names.get("icons", [])
    icon_by_name = {s.name: s for s in icons_gf.sprites}
    icons_str = ",\n    ".join(
        em.sprite_literal(icon_by_name[n], icons_gf.cell_w, icons_gf.cell_h) for n in icon_names
    )

    egg_gf = _load_global(assets_root, "egg")
    egg_by_name = {s.name: s for s in egg_gf.sprites}
    egg_names = spec.global_names.get("egg", ["egg_a", "egg_b"])
    egg_str = ",\n    ".join(
        em.sprite_literal(egg_by_name[n], egg_gf.cell_w, egg_gf.cell_h) for n in egg_names
    )

    effects_gf = _load_global(assets_root, "effects")
    effect_by_name = {s.name: s for s in effects_gf.sprites}
    effect_names = spec.global_names.get("effects", [])
    effects_str = ",\n    ".join(
        em.sprite_literal(effect_by_name[n], effects_gf.cell_w, effects_gf.cell_h) for n in effect_names
    )

    items_gf = _load_global(assets_root, "items")
    item_by_name = {s.name: s for s in items_gf.sprites}
    item_names = spec.global_names.get("items", [])
    items_str = ",\n    ".join(
        em.sprite_literal(item_by_name[n], items_gf.cell_w, items_gf.cell_h) for n in item_names
    )

    tombstone_gf = _load_global(assets_root, "tombstone")
    tombstone_sprite = tombstone_gf.sprites[0]
    tombstone_str = em.sprite_literal(tombstone_sprite, tombstone_gf.cell_w, tombstone_gf.cell_h)

    hearts_gf = _load_global(assets_root, "hearts")
    heart_by_name = {s.name: s for s in hearts_gf.sprites}
    hearts_str = ",\n    ".join(
        em.sprite_literal(heart_by_name[n], hearts_gf.cell_w, hearts_gf.cell_h)
        for n in ("heart_full", "heart_empty")
    )

    font_gf = _load_global(assets_root, "font3x5")
    font_str = ",\n    ".join(
        em.sprite_literal(s, font_gf.cell_w, font_gf.cell_h) for s in font_gf.sprites
    )
    font_count = len(font_gf.sprites)

    species_strs = [_compile_species(em, assets_root, entry["slug"]) for entry in registry]
    species_array = ",\n".join(species_strs)

    game_rules_str = _compile_game_rules(spec)

    content_hash = _fnv1a(bytes(em.hash_input))

    out = [HEADER.format(content_hash=content_hash)]
    out.append(f"\npub static ICONS: [Sprite; {len(icon_names)}] = [\n    {icons_str},\n];\n")
    out.append(_icon_module(icon_names))
    out.append(f"\npub static EGG: [Sprite; {len(egg_names)}] = [\n    {egg_str},\n];\n")
    out.append(f"\npub static EFFECTS: [Sprite; {len(effect_names)}] = [\n    {effects_str},\n];\n")
    out.append(_effect_module(effect_names))
    out.append(f"\npub static ITEMS: [Sprite; {len(item_names)}] = [\n    {items_str},\n];\n")
    out.append(_item_module(item_names))
    out.append(f"\npub static TOMBSTONE: Sprite = {tombstone_str};\n")
    out.append(f"\npub static HEARTS: [Sprite; 2] = [\n    {hearts_str},\n];\n")
    out.append(
        "pub mod heart {\n    pub const FULL: usize = 0;\n    pub const EMPTY: usize = 1;\n}\n"
    )
    out.append(f"\npub static FONT_3X5: [Sprite; {font_count}] = [\n    {font_str},\n];\n")
    out.append(f"\npub static SPECIES: [SpeciesDef; {len(species_strs)}] = [\n{species_array}\n];\n")
    out.append(f"\npub static GAME: GameRules = {game_rules_str};\n")

    return "".join(out)


def _ident(name: str) -> str:
    return name.upper()


def _icon_module(names: list[str]) -> str:
    lines = ["pub mod icon {"]
    for i, n in enumerate(names):
        lines.append(f"    pub const {_ident(n)}: usize = {i};")
    lines.append(f"    pub const COUNT: usize = {len(names)};")
    lines.append("}\n")
    return "\n".join(lines)


def _effect_module(names: list[str]) -> str:
    lines = ["pub mod effect {"]
    for i, n in enumerate(names):
        lines.append(f"    pub const {_ident(n)}: usize = {i};")
    lines.append(f"    pub const COUNT: usize = {len(names)};")
    lines.append("}\n")
    return "\n".join(lines)


def _item_module(names: list[str]) -> str:
    lines = ["pub mod item {"]
    for i, n in enumerate(names):
        lines.append(f"    pub const {_ident(n)}: usize = {i};")
    lines.append(f"    pub const COUNT: usize = {len(names)};")
    lines.append("}\n")
    return "\n".join(lines)
